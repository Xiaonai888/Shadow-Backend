create or replace function public.record_search_analytics_click(
  p_normalized_term text,
  p_search_type text,
  p_searcher_hash text,
  p_target_key text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_now timestamptz := now();
  v_today date := current_date;
  v_group_id bigint;
  v_redirect_group_id bigint;
  v_group_status text;
  v_counted_group_id bigint;
  v_normalized_term text :=
    left(
      lower(trim(coalesce(p_normalized_term, ''))),
      120
    );
  v_search_type text :=
    lower(trim(coalesce(p_search_type, 'all')));
  v_target_key text :=
    left(trim(coalesce(p_target_key, '')), 220);
begin
  if length(v_normalized_term) < 2 then
    return jsonb_build_object(
      'counted',
      false,
      'reason',
      'term_too_short'
    );
  end if;

  if length(trim(coalesce(p_searcher_hash, ''))) < 16 then
    return jsonb_build_object(
      'counted',
      false,
      'reason',
      'missing_searcher'
    );
  end if;

  if length(v_target_key) < 3 then
    return jsonb_build_object(
      'counted',
      false,
      'reason',
      'missing_target'
    );
  end if;

  if v_search_type not in (
    'all',
    'readers',
    'pages',
    'stories',
    'pdfs',
    'posts'
  ) then
    v_search_type := 'all';
  end if;

  select a.group_id
  into v_group_id
  from public.search_term_aliases a
  where a.normalized_alias = v_normalized_term
  limit 1;

  if v_group_id is null then
    return jsonb_build_object(
      'counted',
      false,
      'reason',
      'group_not_found'
    );
  end if;

  select
    g.status,
    g.merged_into
  into
    v_group_status,
    v_redirect_group_id
  from public.search_term_groups g
  where g.id = v_group_id;

  if v_group_status = 'ignored' then
    return jsonb_build_object(
      'counted',
      false,
      'reason',
      'ignored_group',
      'group_id',
      v_group_id
    );
  end if;

  if (
    v_group_status = 'merged' and
    v_redirect_group_id is not null
  ) then
    v_group_id := v_redirect_group_id;
  end if;

  if not exists (
    select 1
    from public.search_analytics_recent_dedupe d
    where d.group_id = v_group_id
      and d.search_type = v_search_type
      and d.searcher_hash = p_searcher_hash
      and d.expires_at > v_now
      and d.last_searched_at >=
        date_trunc('day', v_now)
  ) then
    return jsonb_build_object(
      'counted',
      false,
      'reason',
      'no_recent_search',
      'group_id',
      v_group_id
    );
  end if;

  if exists (
    select 1
    from public.search_analytics_click_dedupe c
    where c.group_id = v_group_id
      and c.search_type = v_search_type
      and c.searcher_hash = p_searcher_hash
      and c.expires_at > v_now
  ) then
    return jsonb_build_object(
      'counted',
      false,
      'reason',
      'recent_duplicate',
      'group_id',
      v_group_id
    );
  end if;

  v_counted_group_id := null;

  insert into public.search_analytics_click_dedupe (
    group_id,
    search_type,
    searcher_hash,
    target_key,
    last_clicked_at,
    expires_at
  )
  values (
    v_group_id,
    v_search_type,
    p_searcher_hash,
    v_target_key,
    v_now,
    v_now + interval '30 minutes'
  )
  on conflict (
    group_id,
    search_type,
    searcher_hash,
    target_key
  )
  do update set
    last_clicked_at = excluded.last_clicked_at,
    expires_at = excluded.expires_at
  where
    public.search_analytics_click_dedupe.expires_at <=
      v_now
  returning group_id
  into v_counted_group_id;

  if v_counted_group_id is null then
    return jsonb_build_object(
      'counted',
      false,
      'reason',
      'recent_duplicate',
      'group_id',
      v_group_id
    );
  end if;

  insert into public.search_analytics_daily (
    search_date,
    group_id,
    search_type,
    searches,
    unique_searchers,
    no_result_searches,
    clicks,
    result_count_total,
    created_at,
    updated_at
  )
  values (
    v_today,
    v_group_id,
    v_search_type,
    0,
    0,
    0,
    1,
    0,
    v_now,
    v_now
  )
  on conflict (
    search_date,
    group_id,
    search_type
  )
  do update set
    clicks =
      public.search_analytics_daily.clicks + 1,
    updated_at = excluded.updated_at;

  return jsonb_build_object(
    'counted',
    true,
    'group_id',
    v_group_id
  );
end;
$$;

