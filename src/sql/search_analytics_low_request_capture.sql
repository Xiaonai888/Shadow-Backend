create table if not exists public.search_analytics_recent_activity (
  id bigint generated by default as identity primary key,
  group_id bigint not null
    references public.search_term_groups(id) on delete cascade,
  search_type text not null default 'all'
    check (
      search_type in (
        'all',
        'readers',
        'pages',
        'stories',
        'pdfs',
        'posts'
      )
    ),
  normalized_term text not null,
  display_term text not null,
  searcher_hash text not null,
  reader_id text,
  result_count integer not null default 0
    check (result_count >= 0),
  searched_at timestamptz not null default now()
);

create table if not exists public.search_analytics_maintenance (
  maintenance_key text primary key,
  last_run_at timestamptz not null
);

insert into public.search_analytics_maintenance (
  maintenance_key,
  last_run_at
)
values (
  'purge',
  '1970-01-01 00:00:00+00'::timestamptz
)
on conflict (maintenance_key) do nothing;

create index if not exists idx_search_activity_searched_at
  on public.search_analytics_recent_activity(searched_at desc);

create index if not exists idx_search_activity_reader
  on public.search_analytics_recent_activity(reader_id, searched_at desc);

create index if not exists idx_search_activity_group
  on public.search_analytics_recent_activity(group_id, searched_at desc);

